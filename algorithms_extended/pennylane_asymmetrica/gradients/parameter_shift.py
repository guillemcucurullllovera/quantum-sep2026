"""Two-term parameter-shift gradient, adapted from the mathematical content
of PennyLane's ``pennylane/gradients/{general_shift_rules,parameter_shift}.py``
(Apache-2.0, Xanadu Quantum Technologies Inc.).

For any gate ``G(theta) = exp(-i*theta/2*P)`` generated by an operator with
eigenvalues :math:`\\pm 1/2` (every standard Pauli rotation -- RX, RY, RZ,
and PennyLane's/Qiskit's two-qubit ``RZZ``/``MultiRZ``), the exact gradient
of an expectation value with respect to ``theta`` is the two-term rule:

.. math::
    \\frac{\\partial \\langle O \\rangle}{\\partial \\theta}
        = \\frac{\\langle O \\rangle_{\\theta+\\pi/2} - \\langle O \\rangle_{\\theta-\\pi/2}}{2}

This is precisely upstream's ``pennylane.gradients.general_shift_rules
.generate_shift_rule`` two-term case (its default, most common path) and
precisely what this platform's own
``algorithms.vqc_qml.ansatz.VQCAnsatz.parameter_shift_feature_grad`` already
implements against its exact numpy-tensor statevector simulator. Upstream's
own code path for this formula is not separable from
``pennylane.tape.QuantumScript``/``pennylane.measurements`` (see
``THIRD_PARTY_NOTICES.md``), so what is reimplemented here is the formula,
applied to a caller-supplied expectation-value callable -- deliberately
built in this module against an *independent* Qiskit ``Statevector``
execution path (see ``reupload_ansatz_z_expectations`` below) rather than
reusing ``VQCAnsatz`` itself, so that the two implementations can be
cross-validated against each other in
``tests/algorithms_extended/test_pennylane_gradients.py`` -- a real,
independent numerical check that both this platform's from-scratch numpy
statevector simulator and Qiskit's own statevector simulator agree on the
same variational circuit's gradient.
"""
from __future__ import annotations

from typing import Callable

import numpy as np
from qiskit import QuantumCircuit
from qiskit.quantum_info import SparsePauliOp, Statevector

from core.errors import ValidationError

from algorithms_extended.pennylane_asymmetrica.templates.embeddings import angle_embedding

ExpvalFn = Callable[[np.ndarray], np.ndarray]


def parameter_shift_gradient(
    expval_fn: ExpvalFn, params: np.ndarray, shift: float = np.pi / 2
) -> np.ndarray:
    """Two-term parameter-shift gradient of a vector-valued expectation
    function with respect to every entry of ``params``.

    Args:
        expval_fn: maps a parameter vector to an array of expectation
            values (e.g. one Z-expectation per qubit).
        params: parameter vector, shape ``(n_params,)``.
        shift: shift amount; ``pi/2`` is exact for any eigenvalue-``+-1/2``
            generator (RX/RY/RZ/RZZ), matching upstream's default.

    Returns:
        Array of shape ``(n_params, *expval_fn(params).shape)``.
    """
    params = np.asarray(params, dtype=float)
    grads = []
    for k in range(len(params)):
        p_plus = params.copy()
        p_plus[k] += shift
        p_minus = params.copy()
        p_minus[k] -= shift
        grads.append((np.asarray(expval_fn(p_plus)) - np.asarray(expval_fn(p_minus))) / 2.0)
    return np.array(grads)


def reupload_ansatz_circuit(
    x: np.ndarray,
    params: np.ndarray,
    n_qubits: int,
    d_layers: int,
    use_rz: bool,
    entanglement: str,
) -> QuantumCircuit:
    """Builds, gate-for-gate, the same data-re-uploading circuit family as
    ``algorithms.vqc_qml.ansatz.VQCAnsatz`` -- but via Qiskit's
    ``QuantumCircuit`` and this module's ported ``angle_embedding`` template,
    an entirely independent code path from that class's numpy
    tensor-contraction statevector simulator. Used only for cross-validating
    the parameter-shift gradient below against ``VQCAnsatz``'s own; not a
    replacement for it.
    """
    x = np.asarray(x, dtype=float)
    x_padded = np.zeros(n_qubits)
    x_padded[: min(len(x), n_qubits)] = x[:n_qubits]
    params = np.asarray(params, dtype=float)
    ppl = n_qubits * (2 if use_rz else 1)
    if len(params) != d_layers * ppl:
        raise ValidationError(
            f"reupload_ansatz_circuit: expected {d_layers * ppl} params, got {len(params)}"
        )

    qc = QuantumCircuit(n_qubits)
    for layer in range(d_layers):
        angle_embedding(qc, x_padded, wires=list(range(n_qubits)), rotation="Y")
        layer_params = params[layer * ppl : (layer + 1) * ppl]
        theta = layer_params[:n_qubits]
        for i in range(n_qubits):
            qc.ry(float(theta[i]), i)
        if use_rz:
            phi = layer_params[n_qubits : 2 * n_qubits]
            for i in range(n_qubits):
                qc.rz(float(phi[i]), i)
        if entanglement == "linear":
            pairs = [(i, i + 1) for i in range(n_qubits - 1)]
        elif entanglement == "ring":
            pairs = [(i, (i + 1) % n_qubits) for i in range(n_qubits)]
        else:
            raise ValidationError(f"reupload_ansatz_circuit: unknown entanglement '{entanglement}'")
        for c, t in pairs:
            qc.cx(c, t)
    return qc


def reupload_ansatz_z_expectations(
    x: np.ndarray,
    params: np.ndarray,
    n_qubits: int,
    d_layers: int = 2,
    use_rz: bool = True,
    entanglement: str = "ring",
) -> np.ndarray:
    """Per-qubit <Z> expectation values of ``reupload_ansatz_circuit``, via
    Qiskit's exact ``Statevector`` simulator."""
    qc = reupload_ansatz_circuit(x, params, n_qubits, d_layers, use_rz, entanglement)
    sv = Statevector(qc)
    z = np.zeros(n_qubits)
    for i in range(n_qubits):
        # Qiskit Pauli-string convention: leftmost character is the highest-
        # indexed qubit, rightmost is qubit 0.
        label = ["I"] * n_qubits
        label[n_qubits - 1 - i] = "Z"
        op = SparsePauliOp("".join(label))
        z[i] = float(sv.expectation_value(op).real)
    return z
